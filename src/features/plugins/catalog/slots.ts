export type PluginSlotId = (typeof SLOT_SEEDS)[number][0]

export type PluginPlatform = 'ios' | 'android' | 'web'

export type PluginSlotDefinition = {
  readonly id: PluginSlotId
  readonly group: PluginSlotGroupId
  readonly title: string
  readonly description: string
  readonly platforms: readonly PluginPlatform[]
  /**
   * Minimal read-only context fields exposed to the slot, matching the slot
   * catalog in the design document.
   */
  readonly contextType: string
  readonly capabilities: readonly string[]
  readonly sinceHostApi: number
  readonly stability: 'stable'
  readonly notes: string
}

export const PLUGIN_PLATFORMS: readonly PluginPlatform[] = [
  'ios',
  'android',
  'web',
]

const PLATFORM_SCOPE: Record<
  PluginSlotPlatformScope,
  readonly PluginPlatform[]
> = {
  all: ['ios', 'android', 'web'],
  native: ['ios', 'android'],
  web: ['web'],
}

export const SLOT_CATALOG: readonly PluginSlotDefinition[] = SLOT_SEEDS.map(
  ([id, group, title, scope, contextType, capabilities]) => ({
    id,
    group,
    title,
    description: `宿主在${title}位置渲染插件内容；上下文仅包含最小化只读字段。`,
    platforms: PLATFORM_SCOPE[scope],
    contextType,
    capabilities,
    sinceHostApi: 2,
    stability: 'stable',
    notes: '',
  }),
)

export const PLUGIN_SLOT_IDS: readonly PluginSlotId[] = SLOT_SEEDS.map(
  entry => entry[0],
)

export function isPluginSlotId(value: unknown): value is PluginSlotId {
  return (
    typeof value === 'string' &&
    (PLUGIN_SLOT_IDS as readonly string[]).includes(value)
  )
}
